type I18nValue = {
  locale: LocaleCode;
  meta: LocaleMeta;
  setLocale: (code: LocaleCode) => void;
  t: (key: string, vars?: Record<string, string | number>) => string;
};

const I18nContext = createContext<I18nValue | null>(null);
const STORAGE_KEY = "rootwise_locale";

function interpolate(text: string, vars?: Record<string, string | number>) {
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (match, key) =>
    vars[key] !== undefined ? String(vars[key]) : match,
  );
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<LocaleCode>(() => {
    const saved = localStorage.getItem(STORAGE_KEY) as LocaleCode | null;
    return saved && DICTS[saved] ? saved : "es";
  });

  useEffect(() => {
    localStorage.setItem(STORAGE_KEY, locale);
    document.documentElement.lang = locale === "ash" ? "es-PE" : `${locale}-PE`;
    window.dispatchEvent(new CustomEvent("rootwise:locale", { detail: locale }));
  }, [locale]);

  const setLocale = useCallback((code: LocaleCode) => {
    if (DICTS[code]) setLocaleState(code);
  }, []);

  const t = useCallback(
    (key: string, vars?: Record<string, string | number>) => {
      const value = DICTS[locale]?.[key] ?? DICTS.es[key] ?? key;
      return interpolate(value, vars);
    },
    [locale],
  );

  const meta = useMemo(
    () => LOCALES.find((item) => item.code === locale) || LOCALES[0],
    [locale],
  );

  const value = useMemo(() => ({ locale, meta, setLocale, t }), [locale, meta, setLocale, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const context = useContext(I18nContext);
  if (!context) throw new Error("useI18n debe usarse dentro de I18nProvider");
  return context;
}
